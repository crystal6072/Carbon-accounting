/** 递归展开为扁平行业表：id = `IND + 行业编码`，层级由嵌套深度推导 */
function buildIndustries(nodes: RawIndustryNode[], parentId: string | null, level: number): IndustryItem[] {
  const out: IndustryItem[] = []
  nodes.forEach(([code, name, children], index) => {
    const id = `IND${code}`
    out.push({
      id,
      code,
      name,
      level: Math.min(level, 4) as IndustryLevel,
      parentId,
      sortNo: index + 1,
      description: '',
      status: 'enabled',
      createdBy: '系统内置',
      createdAt: BUILT_IN_AT,
      updatedBy: '系统内置',
      updatedAt: BUILT_IN_AT,
    })
    if (children && children.length > 0) {
      out.push(...buildIndustries(children, id, level + 1))
    }
  })
  return out
}

