/** 递归展开为扁平分类表：id = `PC + 分类编码`，层级由嵌套深度推导 */
function buildCategories(nodes: RawCategoryNode[], parentId: string | null, level: number): CategoryItem[] {
  const out: CategoryItem[] = []
  nodes.forEach(([code, name, children], index) => {
    const id = `PC${code}`
    out.push({
      id,
      code,
      name,
      parentId,
      level: Math.min(level, 3) as CategoryLevel,
      sortNo: index + 1,
      status: 'enabled',
      remark: '',
      createdBy: '系统内置',
      createdAt: BUILT_IN_AT,
      updatedAt: BUILT_IN_AT,
    })
    if (children && children.length > 0) {
      out.push(...buildCategories(children, id, level + 1))
    }
  })
  return out
}

